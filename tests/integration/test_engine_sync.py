import json
import os
import subprocess
from pathlib import Path

import pytest

from tools.engine_sync import (
    MANIFEST_NAME,
    RENDERED_DIR,
    TRANSFORM_VERSION,
    EngineSyncError,
    check_manifest,
    engine_pin,
    fetch_engine,
    head_commit,
    load_arm,
    sync_engine,
)

pytestmark = pytest.mark.integration

ROOT = Path(__file__).resolve().parents[2]
ARM = ROOT / "arms" / "engine-ornith15-9b.json"


def _origin(tmp_path: Path) -> tuple[Path, str]:
    origin = tmp_path / "origin"
    origin.mkdir()
    for argv in (
        ("init", "-q", "-b", "main"),
        ("config", "user.email", "t@example.com"),
        ("config", "user.name", "t"),
    ):
        subprocess.run(["git", *argv], cwd=origin, check=True, capture_output=True, text=True)
    (origin / "README.md").write_text("readme\n")
    subprocess.run(["git", "add", "README.md"], cwd=origin, check=True, capture_output=True, text=True)
    subprocess.run(["git", "commit", "-q", "-m", "one"], cwd=origin, check=True, capture_output=True, text=True)
    commit = subprocess.run(
        ["git", "-C", str(origin), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    return origin, commit


def _doc_origin(tmp_path: Path) -> tuple[Path, str]:
    origin = tmp_path / "doc-origin"
    (origin / "docs").mkdir(parents=True)
    for argv in (
        ("init", "-q", "-b", "main"),
        ("config", "user.email", "t@example.com"),
        ("config", "user.name", "t"),
    ):
        subprocess.run(["git", *argv], cwd=origin, check=True, capture_output=True, text=True)
    (origin / "README.md").write_text("readme\n")
    (origin / "docs" / "usage.md").write_text("usage\n")
    (origin / "docs" / "glossary.md").write_text("glossary\n")
    subprocess.run(["git", "add", "README.md", "docs"], cwd=origin, check=True, capture_output=True, text=True)
    subprocess.run(["git", "commit", "-q", "-m", "docs"], cwd=origin, check=True, capture_output=True, text=True)
    commit = subprocess.run(
        ["git", "-C", str(origin), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    return origin, commit


def test_fetch_engine_clones_a_repository_at_a_commit(tmp_path: Path) -> None:
    origin, commit = _origin(tmp_path)
    dest = tmp_path / "checkout"
    fetch_engine(dest, commit, repository=str(origin))
    assert head_commit(dest) == commit
    assert (dest / "README.md").read_text() == "readme\n"


def test_fetch_engine_refuses_a_checkout_at_another_commit(tmp_path: Path) -> None:
    origin, commit = _origin(tmp_path)
    dest = tmp_path / "checkout"
    fetch_engine(dest, commit, repository=str(origin))
    with pytest.raises(EngineSyncError, match="not the pinned"):
        fetch_engine(dest, "0" * 40, repository=str(origin))


def test_sync_records_provenance_for_every_synced_file(tmp_path: Path) -> None:
    origin, commit = _doc_origin(tmp_path)
    sync_engine(origin, tmp_path / "_engine", commit)
    rows = (tmp_path / "PROVENANCE.md").read_text()
    for dest in ("README.md", "usage.md", "glossary.md"):
        assert rows.count(f"| _engine/{dest} | satyrn-engine @ {commit} |") == 1
    rendered_source = (
        f"rendered from satyrn-engine @ {commit} by tools/engine_sync.py ({TRANSFORM_VERSION})"
    )
    for dest in ("README.md", "usage.md", "glossary.md"):
        assert rows.count(f"| _engine/{RENDERED_DIR}/{dest} | {rendered_source} |") == 1
    manifest_source = f"generated by tools/engine_sync.py from satyrn-engine @ {commit}"
    assert rows.count(f"| _engine/manifest.json | {manifest_source} |") == 1


def test_sync_refuses_a_dirty_engine_doc(tmp_path: Path) -> None:
    origin, commit = _doc_origin(tmp_path)
    (origin / "docs" / "usage.md").write_text("locally modified\n")
    with pytest.raises(EngineSyncError, match="uncommitted changes"):
        sync_engine(origin, tmp_path / "_engine", commit)


def _checkout() -> Path | None:
    env = os.environ.get("SATYRN_ENGINE_REPO")
    candidate = Path(env) if env else ROOT.parent / "satyrn-engine"
    return candidate if (candidate / ".git").exists() else None


def test_resync_produces_a_clean_manifest(tmp_path: Path) -> None:
    checkout = _checkout()
    if checkout is None:
        pytest.skip("no satyrn-engine checkout")
    commit = engine_pin(load_arm(ARM))
    if head_commit(checkout) != commit:
        pytest.skip(f"checkout is not at the pinned {commit}")
    manifest = sync_engine(checkout, tmp_path / "_engine", commit, record_provenance=False)
    assert check_manifest(tmp_path / "_engine", commit) == []
    assert manifest["engine_commit"] == commit
    assert manifest == json.loads((ROOT / "_engine" / MANIFEST_NAME).read_text())
